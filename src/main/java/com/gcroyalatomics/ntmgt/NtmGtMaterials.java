package com.gcroyalatomics.ntmgt;

import com.gregtechceu.gtceu.api.data.chemical.material.Material;
import com.gregtechceu.gtceu.api.data.chemical.material.event.PostMaterialEvent;
import com.gregtechceu.gtceu.api.data.tag.TagPrefix;
import com.gregtechceu.gtceu.api.registry.GTRegistries;
import com.gregtechceu.gtceu.utils.memoization.GTMemoizer;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.ItemLike;
import net.minecraft.world.level.block.Block;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.function.Supplier;

/**
 * NTM items become GT's own items for a (tag prefix, material) pair, the way GT uses
 * minecraft:iron_ingot as its iron ingot. GT then does not register a duplicate, puts the NTM item
 * into its material tags and builds every generated recipe (macerator, extractor, bender, ...) on it.
 * Forms NTM does not have (rods, screws, foils, ...) stay GT items.
 *
 * <p>The table is {@code /ntmgt/material_links.tsv}, generated by {@code tools/gen_links.py}.
 */
public final class NtmGtMaterials {
    private static final String TABLE = "/ntmgt/material_links.tsv";

    private NtmGtMaterials() {}

    public static void onPostMaterial(PostMaterialEvent event) {
        NtmGtNewMaterials.extendGtElements();
        int linked = 0, skipped = 0;
        for (String[] row : readTable()) {
            TagPrefix prefix = GTRegistries.TAG_PREFIXES.get(ResourceLocation.fromNamespaceAndPath("gtceu", row[0]));
            Material material = com.gcroyalatomics.ntmgt.compat.MaterialNames.gt(row[1]);
            ResourceLocation itemId = ResourceLocation.parse(row[2]);
            if (prefix == null || material == null) {
                NtmGt.LOGGER.warn("[ntmgt] unknown GT prefix/material {} {} for {}", row[0], row[1], itemId);
                skipped++;
                continue;
            }
            boolean isBlock = prefix.doGenerateBlock();
            // Only take over forms GT would generate itself; otherwise GT has no recipes for it anyway.
            if (isBlock ? !prefix.doGenerateBlock(material) : !prefix.doGenerateItem(material)) {
                NtmGt.LOGGER.debug("[ntmgt] GT has no {} for {}, {} stays NTM-only", row[0], row[1], itemId);
                skipped++;
                continue;
            }
            Supplier<? extends ItemLike> item = isBlock
                    ? GTMemoizer.memoizeBlockSupplier(() -> block(itemId))
                    : () -> BuiltInRegistries.ITEM.get(itemId);
            prefix.setIgnored(material, List.of(item));
            linked++;
        }
        NtmGt.LOGGER.info("[ntmgt] linked {} NTM items into GT materials, {} rows skipped", linked, skipped);
    }

    private static Block block(ResourceLocation id) {
        if (!BuiltInRegistries.BLOCK.containsKey(id)) {
            throw new IllegalStateException("[ntmgt] NTM block " + id + " is missing");
        }
        return BuiltInRegistries.BLOCK.get(id);
    }

    private static List<String[]> readTable() {
        try (InputStream in = NtmGtMaterials.class.getResourceAsStream(TABLE)) {
            if (in == null) throw new IllegalStateException("[ntmgt] " + TABLE + " is missing from the jar");
            return new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8)).lines()
                    .filter(l -> !l.isBlank() && !l.startsWith("#"))
                    .map(l -> l.split("\t"))
                    .toList();
        } catch (IOException e) {
            throw new IllegalStateException("[ntmgt] cannot read " + TABLE, e);
        }
    }
}
