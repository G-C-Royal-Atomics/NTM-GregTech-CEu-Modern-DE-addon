"""Build src/main/resources/ntmgt/material_links.tsv: NTM item -> GT (prefix, material).

Input: notes/ntm-tags.tsv (tools/ntm_tags.py) and notes/gt-materials.txt (GT material ids).
Whether GT really has that form for the material is checked in game (NtmGtMaterials), not here.
"""
import sys

FORMS = {  # NTM c: tag folder -> GT tag prefix id
    "ingots": "ingot", "dusts": "dust", "tiny_dusts": "tiny_dust", "nuggets": "nugget",
    "plates": "plate", "storage_blocks": "block", "gems": "gem", "fine_wires": "fine_wire",
    "bolts": "bolt", "raw_materials": "raw",
}
ALIAS = {  # NTM tag material name -> GT material id
    "aluminum": "aluminium", "pvc": "polyvinyl_chloride",
    "actinium_227": "actinium", "radium_226": "radium", "technetium_99": "technetium",
    "neptunium_237": "neptunium", "polonium_210": "polonium", "americium_241": "americium",
}
SKIP = {  # tags whose item is not really that form/material in NTM
    "ingots/borax", "ingots/coltan", "ingots/malachite", "ingots/rare_earth", "ingots/redstone",
    "ingots/neodymium", "ingots/sodium", "ingots/strontium", "ingots/slag", "ingots/carbon",
    "ingots/latex", "dusts/coltan", "dusts/quartz", "storage_blocks/carbon", "storage_blocks/quartz",
}

gt = set(open(sys.argv[2]).read().split())
rows, seen_item, seen_entry = [], set(), set()
for line in open(sys.argv[1]):
    kind, form, mat, items = line.rstrip("\n").split("\t")
    if kind != "item" or form not in FORMS or f"{form}/{mat}" in SKIP:
        continue
    gmat = ALIAS.get(mat, mat)
    if gmat not in gt:
        continue
    cands = [i for i in items.split() if i.startswith("hbm:") and not i.endswith("?")]
    if not cands:
        continue
    item, entry = cands[0], (FORMS[form], gmat)
    if item in seen_item or entry in seen_entry:
        continue
    seen_item.add(item); seen_entry.add(entry)
    rows.append((FORMS[form], gmat, item))

out = sys.argv[3]
with open(out, "w") as f:
    f.write("# GT tag prefix\tGT material\tNTM item  (generated by tools/gen_links.py)\n")
    for r in sorted(rows):
        f.write("\t".join(r) + "\n")
print(len(rows), "links ->", out)
